#include <iostream>
using namespace std;
int main() {
    int a = 10;
    double b = 3.5;
    double result = a + b;
    cout << "int a = " << a << endl;
    cout << "double b = " << b << endl;
    cout << "Result (a + b) = " << result << endl;
    cout << "double b assigned to int c = " << c << endl;
    return 0;
}
